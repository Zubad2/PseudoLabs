const CREDIT = "Generated by PseudoEngine";

const crcTable = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();

const crc32 = (bytes) => {
  let c = 0xffffffff;
  for (let i = 0; i < bytes.length; i++)
    c = crcTable[(c ^ bytes[i]) & 255] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
};

const latin1 = (s) => Uint8Array.from(String(s), (ch) => ch.charCodeAt(0) & 255);
const u32 = (n) => new Uint8Array([n >>> 24, (n >>> 16) & 255, (n >>> 8) & 255, n & 255]);

function pngWithText(bytes, entries) {
  const sig = [137, 80, 78, 71, 13, 10, 26, 10];
  if (bytes.length < 33 || sig.some((b, i) => bytes[i] !== b)) return bytes;
  for (const [key, text] of Object.entries(entries)) {
    const body = new Uint8Array([...latin1(key), 0, ...latin1(text)]);
    const typed = new Uint8Array([...latin1("tEXt"), ...body]);
    parts.push(u32(body.length), typed, u32(crc32(typed)));
  }
  parts.push(bytes.subarray(33));
  const out = new Uint8Array(parts.reduce((n, p) => n + p.length, 0));
  let at = 0;
  for (const p of parts) {
    out.set(p, at);
    at += p.length;
  }
  return out;
}

function pngBlob(canvas, extra) {
  const raw = atob(canvas.toDataURL("image/png").split(",")[1]);
  const bytes = Uint8Array.from(raw, (c) => c.charCodeAt(0));
  const tagged = pngWithText(bytes, {
    Software: "PseudoEngine",
    Comment: CREDIT,
    ...extra,
  });
  return new Blob([tagged], { type: "image/png" });
}

function saveBlob(blob, name) {
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob);
  a.download = name;
  a.click();
  setTimeout(() => URL.revokeObjectURL(a.href), 1000);
}

const download = (canvas, name, extra) => saveBlob(pngBlob(canvas, extra), name);
const saveText = (text, name) =>
  saveBlob(new Blob([text], { type: "text/plain" }), name);
